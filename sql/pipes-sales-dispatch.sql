-- Link physical bundle dispatches to customer sales orders, without changing legacy dispatch records.
-- Each bundle dispatch may satisfy at most one sales order line.
-- Returns (when ACCEPTED after inspection) reverse delivered quantity in reporting.
CREATE TABLE IF NOT EXISTS pipe_sales_dispatch_links(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 sales_order_id BIGINT NOT NULL,
 sales_order_line_id BIGINT NOT NULL REFERENCES pipe_sales_order_lines(id),
 dispatch_id BIGINT NOT NULL UNIQUE REFERENCES warehouse_bundle_dispatches(id),
 bundle_id BIGINT NOT NULL UNIQUE REFERENCES warehouse_bundles(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),
 linked_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(organization_id,sales_order_id) REFERENCES pipe_sales_orders(organization_id,id)
);
CREATE INDEX IF NOT EXISTS ix_sales_dispatch_order ON pipe_sales_dispatch_links(organization_id,sales_order_id);
