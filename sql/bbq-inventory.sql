-- BBQ Pav Bhaji recipe-based stock ledger. Additive only; does not alter Hindustan Pipes inventory.
-- Canonical units: gram (g), millilitre (ml), piece. Quantities stored to 3 decimals.
CREATE TABLE IF NOT EXISTS bbq_inventory_items(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 code TEXT NOT NULL,
 name TEXT NOT NULL,
 unit TEXT NOT NULL CHECK(unit IN ('g','ml','piece')),
 quantity_on_hand NUMERIC(16,3) NOT NULL DEFAULT 0 CHECK(quantity_on_hand>=0),
 reorder_level NUMERIC(16,3) NOT NULL DEFAULT 0 CHECK(reorder_level>=0),
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,code),
 UNIQUE(organization_id,id)
);
CREATE TABLE IF NOT EXISTS bbq_menu_recipes(
 organization_id INTEGER NOT NULL,
 menu_item_id BIGINT NOT NULL,
 inventory_item_id BIGINT NOT NULL,
 qty_per_dish NUMERIC(16,3) NOT NULL CHECK(qty_per_dish>0),
 PRIMARY KEY(organization_id,menu_item_id,inventory_item_id),
 FOREIGN KEY(organization_id,menu_item_id) REFERENCES pos_menu_items(organization_id,id),
 FOREIGN KEY(organization_id,inventory_item_id) REFERENCES bbq_inventory_items(organization_id,id)
);
CREATE TABLE IF NOT EXISTS bbq_inventory_movements(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 inventory_item_id BIGINT NOT NULL,
 order_id BIGINT,
 quantity_delta NUMERIC(16,3) NOT NULL CHECK(quantity_delta<>0),
 reason TEXT NOT NULL CHECK(reason IN ('OPENING','PURCHASE','ADJUSTMENT','COUNT_ADJUSTMENT','WASTE','ORDER_CONSUMPTION','CANCEL_RESTORE')),
 reference TEXT,
 recorded_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 FOREIGN KEY(organization_id,inventory_item_id) REFERENCES bbq_inventory_items(organization_id,id),
 FOREIGN KEY(organization_id,order_id) REFERENCES pos_orders(organization_id,id)
);
CREATE TABLE IF NOT EXISTS bbq_inventory_order_usage(
 organization_id INTEGER NOT NULL,
 order_id BIGINT NOT NULL,
 inventory_item_id BIGINT NOT NULL,
 quantity_used NUMERIC(16,3) NOT NULL CHECK(quantity_used>0),
 disposition TEXT NOT NULL DEFAULT 'CONSUMED' CHECK(disposition IN ('CONSUMED','RESTORED','WASTED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY(organization_id,order_id,inventory_item_id),
 FOREIGN KEY(organization_id,order_id) REFERENCES pos_orders(organization_id,id),
 FOREIGN KEY(organization_id,inventory_item_id) REFERENCES bbq_inventory_items(organization_id,id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_bbq_order_consumption_once
 ON bbq_inventory_movements(organization_id,order_id,inventory_item_id,reason)
 WHERE reason IN ('ORDER_CONSUMPTION','CANCEL_RESTORE');
CREATE INDEX IF NOT EXISTS ix_bbq_stock_movements_date ON bbq_inventory_movements(organization_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_bbq_recipes_menu ON bbq_menu_recipes(organization_id,menu_item_id);
