-- Hindustan Pipes sales planning and manual income register. Apply to isolated staging only.
-- Booking a sales order does NOT reserve inventory, dispatch goods, or create journal vouchers.
CREATE TABLE IF NOT EXISTS pipe_sales_orders (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 order_number TEXT NOT NULL,
 customer_name TEXT NOT NULL CHECK (length(trim(customer_name)) BETWEEN 2 AND 150),
 customer_phone TEXT,
 status TEXT NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN','CANCELLED')),
 notes TEXT,
 order_date DATE NOT NULL DEFAULT CURRENT_DATE,
 created_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,order_number),
 UNIQUE(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_sales_order_lines (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 sales_order_id BIGINT NOT NULL,
 product_id BIGINT NOT NULL,
 quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 10000),
 unit_rate NUMERIC(14,2) NOT NULL CHECK(unit_rate>=0),
 line_total NUMERIC(16,2) NOT NULL CHECK(line_total>=0),
 UNIQUE(sales_order_id,product_id),
 FOREIGN KEY(organization_id,sales_order_id) REFERENCES pipe_sales_orders(organization_id,id),
 FOREIGN KEY(organization_id,product_id) REFERENCES pipe_products(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_income_register (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 income_type TEXT NOT NULL CHECK(income_type IN ('SCRAP_SALE','MISC_INCOME')),
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 details TEXT NOT NULL CHECK(length(trim(details)) BETWEEN 3 AND 500),
 reference TEXT,
 income_date DATE NOT NULL DEFAULT CURRENT_DATE,
 recorded_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_pipe_sales_orders_recent ON pipe_sales_orders(organization_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_pipe_income_recent ON pipe_income_register(organization_id,income_date DESC);
