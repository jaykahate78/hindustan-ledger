-- Warehouse dispatch audit, additive migration. Apply to staging branch first.
-- A bundle is dispatched once, with an immutable linked dispatch event.
-- Original warehouse_lots.quantity remains the original receipt quantity.
-- Available stock is calculated from lot quantity less dispatched bundle quantities.
CREATE TABLE IF NOT EXISTS warehouse_bundle_dispatches(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 bundle_id BIGINT NOT NULL UNIQUE REFERENCES warehouse_bundles(id),
 dispatch_code TEXT NOT NULL,
 recipient TEXT NOT NULL CHECK(length(trim(recipient)) BETWEEN 2 AND 120),
 vehicle_number TEXT,
 delivery_reference TEXT,
 notes TEXT,
 dispatched_by BIGINT REFERENCES app_users(id),
 dispatched_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,dispatch_code)
);
CREATE INDEX IF NOT EXISTS ix_bundle_dispatches_org_recent ON warehouse_bundle_dispatches(organization_id,dispatched_at DESC);
