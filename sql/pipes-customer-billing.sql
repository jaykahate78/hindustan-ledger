-- Staging-only commercial records: tax treatment must be approved before legal invoice issuance.
CREATE TABLE IF NOT EXISTS pipe_customer_invoices(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 sales_order_id BIGINT NOT NULL,
 invoice_number TEXT NOT NULL,
 customer_name TEXT NOT NULL,
 subtotal NUMERIC(16,2) NOT NULL CHECK(subtotal>0),
 status TEXT NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','VOID')),
 created_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,invoice_number),
 UNIQUE(organization_id,id),
 FOREIGN KEY(organization_id,sales_order_id) REFERENCES pipe_sales_orders(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_invoice_lines(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 invoice_id BIGINT NOT NULL,
 sales_dispatch_link_id BIGINT NOT NULL UNIQUE REFERENCES pipe_sales_dispatch_links(id),
 quantity INTEGER NOT NULL CHECK(quantity>0),
 unit_rate NUMERIC(14,2) NOT NULL CHECK(unit_rate>=0),
 line_total NUMERIC(16,2) NOT NULL CHECK(line_total>=0),
 FOREIGN KEY(organization_id,invoice_id) REFERENCES pipe_customer_invoices(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_customer_payments(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 invoice_id BIGINT NOT NULL,
 receipt_number TEXT NOT NULL,
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 payment_method TEXT NOT NULL CHECK(payment_method IN ('CASH','UPI','BANK','CHEQUE')),
 reference TEXT,
 received_by BIGINT REFERENCES app_users(id),
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,receipt_number),
 FOREIGN KEY(organization_id,invoice_id) REFERENCES pipe_customer_invoices(organization_id,id)
);
CREATE INDEX IF NOT EXISTS ix_customer_invoices_recent ON pipe_customer_invoices(organization_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_customer_payments_invoice ON pipe_customer_payments(organization_id,invoice_id);
