-- Additive procurement and expense tracking for Hindustan Pipes; staging first.
CREATE TABLE IF NOT EXISTS pipe_suppliers(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 name TEXT NOT NULL CHECK(length(trim(name)) BETWEEN 2 AND 150),
 phone TEXT, gstin TEXT, created_at TIMESTAMPTZ DEFAULT now(),
 UNIQUE(organization_id,id),UNIQUE(organization_id,name)
);
CREATE TABLE IF NOT EXISTS pipe_purchase_orders(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 supplier_id BIGINT NOT NULL,
 po_number TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'OPEN' CHECK(status IN ('OPEN','PART_RECEIVED','RECEIVED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 notes TEXT,
 UNIQUE(organization_id,po_number),UNIQUE(organization_id,id),
 FOREIGN KEY(organization_id,supplier_id) REFERENCES pipe_suppliers(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_purchase_order_lines(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 po_id BIGINT NOT NULL,
 raw_material_id BIGINT NOT NULL,
 ordered_quantity NUMERIC(14,3) NOT NULL CHECK(ordered_quantity>0),
 received_quantity NUMERIC(14,3) NOT NULL DEFAULT 0 CHECK(received_quantity>=0 AND received_quantity<=ordered_quantity),
 unit_rate NUMERIC(14,2) NOT NULL CHECK(unit_rate>=0),
 UNIQUE(po_id,raw_material_id),UNIQUE(organization_id,id),
 FOREIGN KEY(organization_id,po_id) REFERENCES pipe_purchase_orders(organization_id,id),
 FOREIGN KEY(organization_id,raw_material_id) REFERENCES raw_materials(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_purchase_receipts(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL,
 po_line_id BIGINT NOT NULL,
 receipt_number TEXT NOT NULL,
 quantity NUMERIC(14,3) NOT NULL CHECK(quantity>0),
 reference TEXT,
 received_by BIGINT REFERENCES app_users(id),
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 UNIQUE(organization_id,receipt_number),
 FOREIGN KEY(organization_id,po_line_id) REFERENCES pipe_purchase_order_lines(organization_id,id)
);
CREATE TABLE IF NOT EXISTS pipe_factory_expenses(
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 category TEXT NOT NULL CHECK(category IN ('TRANSPORT','ELECTRICITY','WATER','WAGES','DIE_MAINTENANCE','DIE_PURCHASE','SCRAP','SECURITY','FACTORY_MAINTENANCE','OTHER')),
 amount NUMERIC(14,2) NOT NULL CHECK(amount>0),
 expense_date DATE NOT NULL DEFAULT CURRENT_DATE,
 reference TEXT,description TEXT,
 recorded_by BIGINT REFERENCES app_users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_pipe_po_recent ON pipe_purchase_orders(organization_id,created_at DESC);
CREATE INDEX IF NOT EXISTS ix_pipe_expenses_recent ON pipe_factory_expenses(organization_id,expense_date DESC);
