-- Additive warehouse return inspection workflow. Apply ONLY to Neon staging first.
-- Full-bundle returns only: no physical stock credited before ADMIN inspection.
-- Accepted returns receive a NEW bundle ID; original dispatch remains immutable.
CREATE TABLE IF NOT EXISTS warehouse_bundle_returns (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 organization_id INTEGER NOT NULL REFERENCES organizations(id),
 dispatch_id BIGINT NOT NULL UNIQUE REFERENCES warehouse_bundle_dispatches(id),
 return_code TEXT NOT NULL,
 status TEXT NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','ACCEPTED','REJECTED')),
 reason TEXT NOT NULL CHECK(length(trim(reason)) BETWEEN 3 AND 500),
 inspection_note TEXT,
 received_by BIGINT REFERENCES app_users(id),
 inspected_by BIGINT REFERENCES app_users(id),
 restock_bundle_id BIGINT UNIQUE REFERENCES warehouse_bundles(id),
 received_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 inspected_at TIMESTAMPTZ,
 UNIQUE(organization_id,return_code),
 CHECK ((status='PENDING' AND inspected_at IS NULL AND restock_bundle_id IS NULL)
    OR (status='REJECTED' AND inspected_at IS NOT NULL AND restock_bundle_id IS NULL)
    OR (status='ACCEPTED' AND inspected_at IS NOT NULL AND restock_bundle_id IS NOT NULL))
);
CREATE INDEX IF NOT EXISTS ix_pipe_returns_org_recent ON warehouse_bundle_returns(organization_id,received_at DESC);
